SET SERVEROUTPUT ON;

CREATE OR REPLACE PROCEDURE SEARCH_EMP
(EID IN NUMBER, ENAME OUT VARCHAR2)
AS
BEGIN
    SELECT ENAME INTO ENAME
    FROM EMP
    WHERE EMPNO = EID;
END;
/

DECLARE
    N VARCHAR2(50);
BEGIN
    SEARCH_EMP(101,N);
    DBMS_OUTPUT.PUT_LINE('Name: ' || N);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Employee Not Found');
END;
/
/
