CREATE TABLE ACCOUNT
(
    ACNO NUMBER,
    CNAME VARCHAR2(50),
    BNAME VARCHAR2(50),
    BALANCE NUMBER
);

CREATE OR REPLACE FUNCTION GET_BAL(AN NUMBER)
RETURN NUMBER
AS
    B NUMBER;
BEGIN
    SELECT BALANCE INTO B
    FROM ACCOUNT
    WHERE ACNO = AN;

    RETURN B;
END;
/

